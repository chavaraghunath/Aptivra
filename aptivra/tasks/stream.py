"""Continual Task Stream Manager with Disjoint Splits and Contamination Safeguards."""

import hashlib
import re
from collections.abc import Callable, Collection, Mapping
from functools import partial
from typing import Literal, NamedTuple

from aptivra.tasks.algo_synth import AlgoSynthTaskFamily
from aptivra.tasks.base import TaskFamily, TaskInstance
from aptivra.tasks.boolean_logic import BooleanLogicTaskFamily
from aptivra.tasks.bug_fixer import BugFixerTaskFamily
from aptivra.tasks.docstring_code import DocstringToCodeTaskFamily
from aptivra.tasks.list_operations import ListOperationsTaskFamily
from aptivra.tasks.modular_arithmetic import ModularArithmeticTaskFamily
from aptivra.tasks.python_microsynth import PythonMicroSynthTaskFamily
from aptivra.tasks.sequence_completion import SequenceCompletionTaskFamily
from aptivra.tasks.state_machines import StateMachineTaskFamily
from aptivra.tasks.string_transforms import StringTransformTaskFamily
from aptivra.tasks.syntax_matching import SyntaxMatchingTaskFamily
from aptivra.tasks.type_inferrer import TypeInferrerTaskFamily

TaskStreamVersion = Literal["v1", "v2"]
CODE_FAMILY_IDS = frozenset(
    {
        "T8_python_microsynth",
        "T9_algo_synth",
        "T10_docstring_code",
        "T11_bug_fixer",
        "T12_type_inferrer",
    }
)
_FUNCTION_NAME_PATTERN = re.compile(r"\bf_[0-9a-f]+_[0-9a-f]+\b")
_QUOTED_STRING_PATTERN = re.compile(
    r"'(?:\\.|[^'\\])*'|\"(?!\"\")(?:\\.|[^\"\\])*\""
)
_NUMBER_PATTERN = re.compile(r"(?<![A-Za-z_])-?\d+(?:\.\d+)?")


def normalized_prompt_template(prompt: str) -> str:
    """Normalize generated parameters while retaining the prompt's program shape."""
    normalized = _FUNCTION_NAME_PATTERN.sub("F", prompt)
    normalized = _QUOTED_STRING_PATTERN.sub("'S'", normalized)
    return _NUMBER_PATTERN.sub("#", normalized)


class TaskStreamSplit(NamedTuple):
    """Container for disjoint splits of a task family."""

    train: list[TaskInstance]
    val: list[TaskInstance]
    test: list[TaskInstance]


class ContinualTaskStream:
    """Manages sequential execution of task families with strict split isolation assertions."""

    def __init__(
        self,
        num_train_per_task: int = 500,
        num_val_per_task: int = 100,
        num_test_per_task: int = 300,
        num_template_ood_test_per_code_family: int | None = None,
        seed: int = 42,
        max_generation_attempts: int = 100,
        version: TaskStreamVersion = "v1",
        family_roles: Mapping[str, str] | None = None,
        headline_roles: Collection[str] | None = None,
    ) -> None:
        self.num_train_per_task = num_train_per_task
        self.num_val_per_task = num_val_per_task
        self.num_test_per_task = num_test_per_task
        if num_template_ood_test_per_code_family is None:
            self.num_template_ood_test_per_code_family = 300 if version == "v2" else 0
        else:
            self.num_template_ood_test_per_code_family = (
                num_template_ood_test_per_code_family
            )
        self.seed = seed
        self.max_generation_attempts = max_generation_attempts
        self.version = version

        if version == "v1":
            # This registry and the v1 materialization path below are frozen because
            # historical experiment records refer to their exact generated bytes.
            self.families = self._v1_families()
        elif version == "v2":
            from aptivra.tasks.v2 import v2_families

            self.families = v2_families()
        else:
            raise ValueError(f"Unsupported task stream version '{version}'.")

        family_ids = {family.family_id for family in self.families}
        if family_roles is None:
            self.family_roles = dict.fromkeys(family_ids, "skill")
        else:
            unknown_family_ids = set(family_roles) - family_ids
            missing_family_ids = family_ids - set(family_roles)
            if unknown_family_ids:
                raise ValueError(
                    "Family roles contain unknown family IDs: "
                    + ", ".join(sorted(unknown_family_ids))
                )
            if missing_family_ids:
                raise ValueError(
                    "Family roles are missing family IDs: "
                    + ", ".join(sorted(missing_family_ids))
                )
            self.family_roles = dict(family_roles)
        selected_headline_roles = set(headline_roles or {"skill"})
        self.headline_task_indices = [
            index
            for index, family in enumerate(self.families)
            if self.family_roles[family.family_id] in selected_headline_roles
        ]
        if not self.headline_task_indices:
            raise ValueError("At least one task family must be headline-eligible.")

        self._splits: dict[str, TaskStreamSplit] = {}
        self._template_ood_splits: dict[str, list[TaskInstance]] = {}
        self._held_out_regression_suite: dict[str, list[TaskInstance]] = {}
        self._generate_all_splits()

    @staticmethod
    def _v1_families() -> list[TaskFamily]:
        """Return the byte-stable historical family registry."""
        return [
            ModularArithmeticTaskFamily(),
            StringTransformTaskFamily(),
            ListOperationsTaskFamily(),
            SyntaxMatchingTaskFamily(),
            BooleanLogicTaskFamily(),
            SequenceCompletionTaskFamily(),
            StateMachineTaskFamily(),
            PythonMicroSynthTaskFamily(),
            AlgoSynthTaskFamily(),
            DocstringToCodeTaskFamily(),
            BugFixerTaskFamily(),
            TypeInferrerTaskFamily(),
        ]

    @staticmethod
    def _instance_hash(instance: TaskInstance) -> str:
        """Unique content hash of task instance prompt and solution."""
        raw = f"{instance.task_family}:{instance.prompt}:{instance.target_solution}"
        return hashlib.sha256(raw.encode("utf-8")).hexdigest()

    def _generate_all_splits(self) -> None:
        """Generates disjoint train, val, and test splits with explicit isolation assertions."""
        if self.version == "v2":
            self._generate_all_splits_v2()
            return
        for idx, family in enumerate(self.families):
            train_seed = self.seed * 1000 + idx * 10 + 1
            val_seed = self.seed * 1000 + idx * 10 + 2
            test_seed = self.seed * 1000 + idx * 10 + 3

            # 1. Generate train instances
            train_instances = family.generate_unique_instances(
                self.num_train_per_task,
                seed=train_seed,
                max_attempts=self.max_generation_attempts,
            )
            train_hashes = {self._instance_hash(inst) for inst in train_instances}

            # 2. Generate val instances, ensuring 0 overlap with train
            val_instances = family.generate_unique_instances(
                self.num_val_per_task,
                seed=val_seed,
                excluded_instances=train_instances,
                max_attempts=self.max_generation_attempts,
            )
            val_hashes = {self._instance_hash(inst) for inst in val_instances}

            # 3. Generate test instances, ensuring 0 overlap with train & val
            test_instances = family.generate_unique_instances(
                self.num_test_per_task,
                seed=test_seed,
                excluded_instances=train_instances + val_instances,
                max_attempts=self.max_generation_attempts,
            )
            test_hashes = {self._instance_hash(inst) for inst in test_instances}

            # Runtime Assertions: Enforce internal split isolation
            assert train_hashes.isdisjoint(val_hashes), (
                f"Data Contamination: Train and Val overlap in {family.family_id}"
            )
            assert train_hashes.isdisjoint(test_hashes), (
                f"Data Contamination: Train and Test overlap in {family.family_id}"
            )
            assert val_hashes.isdisjoint(test_hashes), (
                f"Data Contamination: Val and Test overlap in {family.family_id}"
            )

            split = TaskStreamSplit(train=train_instances, val=val_instances, test=test_instances)
            self._splits[family.family_id] = split
            # Held-out regression suite uses the test split
            self._held_out_regression_suite[family.family_id] = test_instances

    def _generate_all_splits_v2(self) -> None:
        """Materialize v2 with target and normalized-program isolation."""
        for idx, family in enumerate(self.families):
            train_seed = self.seed * 1000 + idx * 10 + 1
            val_seed = self.seed * 1000 + idx * 10 + 2
            test_seed = self.seed * 1000 + idx * 10 + 3
            structural = idx >= 7

            train_instances = self._generate_v2_unique(
                family, self.num_train_per_task, train_seed, structural=structural
            )
            val_instances = self._generate_v2_unique(
                family,
                self.num_val_per_task,
                val_seed,
                excluded_instances=train_instances,
                structural=structural,
            )
            test_instances = self._generate_v2_unique(
                family,
                self.num_test_per_task,
                test_seed,
                excluded_instances=train_instances + val_instances,
                structural=structural,
            )

            split = TaskStreamSplit(
                train=train_instances,
                val=val_instances,
                test=test_instances,
            )
            self._splits[family.family_id] = split
            self._held_out_regression_suite[family.family_id] = test_instances

        if self.num_template_ood_test_per_code_family <= 0:
            return
        from aptivra.tasks.v2 import generate_template_ood_instances

        for idx, family in enumerate(self.families):
            if family.family_id not in CODE_FAMILY_IDS:
                continue
            split = self._splits[family.family_id]
            in_template_instances = split.train + split.val + split.test
            template_ood_instances = self._generate_v2_unique(
                family,
                self.num_template_ood_test_per_code_family,
                self.seed * 1000 + idx * 10 + 4,
                excluded_instances=in_template_instances,
                structural=True,
                generator=partial(generate_template_ood_instances, family),
            )
            in_template_ids = {
                normalized_prompt_template(item.prompt)
                for item in in_template_instances
            }
            template_ood_ids = {
                normalized_prompt_template(item.prompt)
                for item in template_ood_instances
            }
            overlap = in_template_ids & template_ood_ids
            if overlap:
                raise ValueError(
                    f"V2 template-OOD split for '{family.family_id}' overlaps "
                    f"{len(overlap)} in-template prompt templates."
                )
            self._template_ood_splits[family.family_id] = template_ood_instances
            self._held_out_regression_suite[family.family_id] = (
                self._held_out_regression_suite[family.family_id]
                + template_ood_instances
            )

    def _generate_v2_unique(
        self,
        family: TaskFamily,
        count: int,
        seed: int,
        *,
        excluded_instances: list[TaskInstance] | None = None,
        structural: bool,
        generator: Callable[[int, int], list[TaskInstance]] | None = None,
    ) -> list[TaskInstance]:
        """Generate a v2 split with exact-target and optional AST isolation."""
        from aptivra.tasks.structure import structural_hash

        excluded = excluded_instances or []
        excluded_pairs = {(item.prompt, item.target_solution) for item in excluded}
        excluded_targets = {item.target_solution for item in excluded}
        excluded_structures = {
            fingerprint
            for item in excluded
            if (fingerprint := structural_hash(item.target_solution)) is not None
        }
        selected: list[TaskInstance] = []
        selected_pairs: set[tuple[str, str]] = set()
        selected_targets: set[str] = set()
        selected_structures: set[str] = set()

        for attempt in range(self.max_generation_attempts):
            remaining = count - len(selected)
            if remaining <= 0:
                return selected
            generate = generator or family.generate_instances
            candidates = generate(max(remaining * 2, 1), seed + attempt * 10_000)
            for candidate in candidates:
                pair = (candidate.prompt, candidate.target_solution)
                if (
                    pair in excluded_pairs
                    or pair in selected_pairs
                    or candidate.target_solution in excluded_targets
                    or candidate.target_solution in selected_targets
                ):
                    continue
                fingerprint = structural_hash(candidate.target_solution)
                if structural:
                    if fingerprint is None:
                        raise ValueError(
                            f"V2 code family '{family.family_id}' emitted invalid Python."
                        )
                    if (
                        fingerprint in excluded_structures
                        or fingerprint in selected_structures
                    ):
                        continue
                    selected_structures.add(fingerprint)
                selected_pairs.add(pair)
                selected_targets.add(candidate.target_solution)
                selected.append(candidate)
                if len(selected) == count:
                    return selected

        raise ValueError(
            f"V2 task family '{family.family_id}' could generate only {len(selected)} "
            f"of {count} requested isolated instances after "
            f"{self.max_generation_attempts} attempts."
        )

    def get_split(self, family_id: str) -> TaskStreamSplit:
        """Returns the task stream split for a given family ID."""
        if family_id not in self._splits:
            raise KeyError(f"Task family '{family_id}' not found in stream.")
        return self._splits[family_id]

    def get_template_ood_split(self, family_id: str) -> list[TaskInstance]:
        """Return the separate held-out-template test cell for one code family."""
        if family_id not in {family.family_id for family in self.families}:
            raise KeyError(f"Task family '{family_id}' not found in stream.")
        return self._template_ood_splits.get(family_id, [])

    def get_held_out_regression_suite(self, up_to_task_idx: int) -> list[TaskInstance]:
        """Returns held-out test instances for all tasks up to up_to_task_idx (inclusive)."""
        suite: list[TaskInstance] = []
        for i in range(min(up_to_task_idx + 1, len(self.families))):
            fam_id = self.families[i].family_id
            suite.extend(self._held_out_regression_suite[fam_id])
        return suite

    def verify_no_contamination(
        self, candidate_instances: list[TaskInstance], up_to_task_idx: int
    ) -> None:
        """Strict assertion checking candidate instances against the held-out regression suite."""
        regression_suite = self.get_held_out_regression_suite(up_to_task_idx)
        regression_hashes = {self._instance_hash(inst) for inst in regression_suite}
        candidate_hashes = {self._instance_hash(inst) for inst in candidate_instances}

        intersection = candidate_hashes.intersection(regression_hashes)
        assert len(intersection) == 0, (
            f"VIOLATION DETECTED: {len(intersection)} instances in candidate batch "
            "intersect with the held-out regression suite!"
        )
